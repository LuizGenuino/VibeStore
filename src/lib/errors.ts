  MESSAGES[code] ??
  (code.startsWith('23505:')
    ? 'Já existe um registro com este valor.'
    : code.startsWith('23514:')
      ? 'Valor inválido para este campo.'
      : code.startsWith('23503:')
        ? 'Este registro está relacionado a outros dados.'
        : MESSAGES.UNKNOWN)
